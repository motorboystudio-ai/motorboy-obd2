const DTC_TYPE_NIBBLE = { P: 0x2, C: 0x3, B: 0x4, U: 0x5 };
const DTC_NIBBLE_TO_TYPE = { 0x2: 'P', 0x3: 'C', 0x4: 'B', 0x5: 'U' };

/** 'P0301' → [0x21, 0x2d] (16-bit OBD DTC encoding: 0x2000 + decimal). */
export function dtcToHexBytes(code) {
  const m = String(code).toUpperCase().match(/^([PCBU])(\d{4})$/);
  if (!m) throw new Error(`Invalid DTC code: ${code}`);
  const value = (DTC_TYPE_NIBBLE[m[1]] << 12) + parseInt(m[2], 10);
  return [(value >> 8) & 0xff, value & 0xff];
}

/** [0x21, 0x2d] → 'P0301' (or null if not a valid DTC word). */
export function hexToDtcCode(hi, lo) {
  const value = (hi << 8) | lo;
  const type = DTC_NIBBLE_TO_TYPE[value >> 12];
  if (!type) return null;
  return `${type}${String(value & 0x0fff).padStart(4, '0')}`;
}

